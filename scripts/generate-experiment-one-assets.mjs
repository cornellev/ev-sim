import { createHash } from "node:crypto";
import { execFile } from "node:child_process";
import { promises as fs } from "node:fs";
import path from "node:path";
import { promisify } from "node:util";
import { fileURLToPath } from "node:url";

const run = promisify(execFile);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const output = path.join(root, "public", "visual-lab", "experiment-1", "assets");
const blender = process.env.CEV_SIM_BLENDER
    ?? "/Applications/Blender.app/Contents/MacOS/Blender";

const blenderVersion = await run(blender, ["--version"], { maxBuffer: 1024 * 1024 });
if (!blenderVersion.stdout.includes("Blender 4.5.4 LTS") || !blenderVersion.stdout.includes("b3efe983cc58")) {
    throw new Error("Experiment 1 assets require Blender 4.5.4 LTS build b3efe983cc58.");
}

await run(blender, [
    "--background",
    "--factory-startup",
    "--python-exit-code", "1",
    "--python", path.join(root, "scripts", "build-experiment-one-assets.py"),
    "--",
    "--output-dir", output,
], { maxBuffer: 32 * 1024 * 1024 });

const files = (await walk(output)).sort();
const records = [];
for (const file of files) {
    const bytes = await fs.readFile(file);
    records.push({
        path: `/${path.relative(path.join(root, "public"), file).split(path.sep).join("/")}`,
        sizeBytes: bytes.length,
        sha256: createHash("sha256").update(bytes).digest("hex"),
    });
}
const manifest = {
    kind: "cev-sim.visual-lab-asset-manifest",
    version: 1,
    caseId: "experiment-1-room",
    fixtureSource: {
        path: "/app/visual-lab/experiment-one-fixture.json",
        sha256: createHash("sha256").update(await fs.readFile(path.join(root, "app", "visual-lab", "experiment-one-fixture.json"))).digest("hex"),
    },
    blender: { version: "4.5.4 LTS", buildHash: "b3efe983cc58" },
    acquisitionProvenance: {
        origin: "Procedurally authored for Experiment 1 from the repository-owned metric fixture; no external model or texture assets.",
        externalAssets: [],
        generatedBy: [
            "scripts/build-experiment-one-assets.py",
            "scripts/generate-experiment-one-assets.mjs",
        ],
    },
    rendererDerivations: {
        browser: {
            geometry: "GLB export from the editable Blender source with metric UVs applied.",
            materials: "glTF metallic-roughness using the retained base-color and roughness maps.",
        },
        cycles: {
            geometry: "Editable Blender source geometry without an intermediate mesh conversion.",
            materials: "Principled BSDF using the same retained base-color and roughness maps; no intentional material-value substitution.",
        },
        declaredDifferences: [
            "Cycles uses area lights and multi-bounce transport; the browser uses the selected pbr render recipe's ambient, directional, and point lights.",
            "The browser glTF shader and Cycles Principled BSDF are renderer-specific implementations of the same material inputs.",
        ],
    },
    files: records,
};
await fs.writeFile(path.join(output, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);
await fs.writeFile(
    path.join(root, "app", "visual-lab", "ExperimentOneAssetManifest.js"),
    `// Generated by scripts/generate-experiment-one-assets.mjs.\nexport const EXPERIMENT_ONE_ASSET_MANIFEST = Object.freeze(${JSON.stringify(manifest, null, 4)});\n`,
);
console.log(`Recorded ${records.length} Experiment 1 asset files.`);

async function walk(directory) {
    const entries = await fs.readdir(directory, { withFileTypes: true });
    const files = [];
    for (const entry of entries) {
        if (entry.name === "manifest.json") continue;
        const target = path.join(directory, entry.name);
        if (entry.isDirectory()) files.push(...await walk(target));
        else files.push(target);
    }
    return files;
}
