import { createHash } from "node:crypto";
import { spawn } from "node:child_process";
import { promises as fs } from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

import {
    EXPERIMENT_ONE_PATHS,
    EXPERIMENT_ONE_VIEWPOINTS,
} from "../app/visual-lab/ExperimentOneCase.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const blender = process.env.CEV_SIM_BLENDER ?? "/Applications/Blender.app/Contents/MacOS/Blender";
const output = path.join(root, "public", "visual-lab", "experiment-1", "reference");
const full = process.argv.includes("--full");
const baseOnly = process.argv.includes("--base-only");
const limitIndex = process.argv.indexOf("--limit");
const limit = limitIndex >= 0 ? Number(process.argv[limitIndex + 1]) : 0;
const schedulePath = path.join(os.tmpdir(), `cev-sim-experiment-one-cycles-${process.pid}.json`);
const versionOutput = await new Promise((resolve, reject) => {
    const child = spawn(blender, ["--version"], { stdio: ["ignore", "pipe", "inherit"] });
    let stdout = "";
    child.stdout.setEncoding("utf8");
    child.stdout.on("data", (chunk) => { stdout += chunk; });
    child.once("error", reject);
    child.once("exit", (code, signal) => code === 0 ? resolve(stdout) : reject(new Error(`Blender version check exited with ${code ?? signal}`)));
});
if (!versionOutput.includes("Blender 4.5.4 LTS") || !versionOutput.includes("b3efe983cc58")) {
    throw new Error("Experiment 1 reference capture requires Blender 4.5.4 LTS build b3efe983cc58.");
}
const schedule = {
    viewpoints: EXPERIMENT_ONE_VIEWPOINTS,
    paths: EXPERIMENT_ONE_PATHS,
    conditions: ["ordinary-environment", "directional-challenge"],
    editVariants: baseOnly ? ["base"] : ["base", "chair-translated", "chair-rotated", "light-moved"],
};
await fs.writeFile(schedulePath, `${JSON.stringify(schedule)}\n`);
try {
    const args = [
        path.join(root, "public", "visual-lab", "experiment-1", "assets", "experiment-1-room.blend"),
        "--background",
        "--python-exit-code", "1",
        "--python", path.join(root, "scripts", "render-experiment-one-cycles.py"),
        "--",
        "--schedule", schedulePath,
        "--output-dir", output,
        ...(full ? ["--full"] : []),
        ...(limit > 0 ? ["--limit", String(limit)] : []),
    ];
    await new Promise((resolve, reject) => {
        const child = spawn(blender, args, { stdio: ["ignore", "ignore", "inherit"] });
        child.once("error", reject);
        child.once("exit", (code, signal) => code === 0 ? resolve() : reject(new Error(`Blender exited with ${code ?? signal}`)));
    });
} finally {
    await fs.unlink(schedulePath).catch(() => {});
}

const recordsDocument = JSON.parse(await fs.readFile(path.join(output, "render-records.json"), "utf8"));
const records = [];
const files = {};
for (const record of recordsDocument.records) {
    const displayFiles = await retained(record.displayFiles);
    const linearFiles = await retained(record.linearFiles);
    Object.assign(files, ...displayFiles.map((entry) => ({ [entry.url]: entry.sha256 })), ...linearFiles.map((entry) => ({ [entry.url]: entry.sha256 })));
    records.push({
        ...record,
        displayFiles: displayFiles.map((entry) => entry.url),
        linearFiles: linearFiles.map((entry) => entry.url),
    });
}
const manifest = {
    kind: "cev-sim.visual-lab-cycles-capture-manifest",
    version: 1,
    caseId: "experiment-1-room",
    blender: { version: "4.5.4 LTS", buildHash: "b3efe983cc58" },
    completeMotionSchedules: full && limit === 0,
    renderer: recordsDocument.renderer,
    image: { width: 1280, height: 720, displayMediaType: "image/png", linearMediaType: "image/x-exr" },
    outputs: records,
    files: Object.fromEntries(Object.entries(files).sort(([left], [right]) => left.localeCompare(right))),
};
await fs.writeFile(path.join(output, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);
await fs.writeFile(
    path.join(root, "app", "visual-lab", "ExperimentOneCyclesMediaManifest.js"),
    `// Generated by scripts/generate-experiment-one-cycles.mjs.\nexport const EXPERIMENT_ONE_CYCLES_MEDIA_MANIFEST = Object.freeze(${JSON.stringify(manifest, null, 4)});\n`,
);
console.log(`Recorded ${Object.keys(files).length} pinned Cycles artifacts.`);

async function retained(paths) {
    const result = [];
    for (const file of paths) {
        const bytes = await fs.readFile(file);
        result.push({
            url: `/${path.relative(path.join(root, "public"), file).split(path.sep).join("/")}`,
            sha256: createHash("sha256").update(bytes).digest("hex"),
        });
    }
    return result;
}
